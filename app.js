const heroBadges = document.querySelector("#heroBadges");
const progressText = document.querySelector("#progressText");
const progressBar = document.querySelector("#progressBar");

function localizeDay(day) {
  const translation = itineraryTranslations[state.lang]?.[day.id];
  return translation ? { ...day, ...translation, id: day.id, date: day.date } : day;
}

function getDay() {
  const day = itinerary.find((item) => item.id === state.selectedDay) || itinerary[0];
  return localizeDay(day);
}

function getLocalizedRoutes(dayId) {
  const routes = routeLinks[dayId] || [];
  const translations = routeTranslations[state.lang]?.[dayId] || [];

  return routes.map((item, index) => {
    const translation = translations[index] || {};
    return {
      ...item,
      time: translation.time || item.time,
      title: translation.title || item.title,
      note: translation.note || item.note,
      links: (item.links || []).map((link, linkIndex) => ({
        ...link,
        label: translation.links?.[linkIndex] || link.label
      })),
      alts: (item.alts || []).map((link, linkIndex) => ({
        ...link,
        label: translation.alts?.[linkIndex] || link.label
      }))
    };
  });
}

function shotKey(dayId, index) {
  return `${dayId}-${index}`;
}

function save() {
  localStorage.setItem(storageKey, JSON.stringify(state.checked));
}

function countDayDone(day) {
  return day.shots.filter((_, index) => state.checked[shotKey(day.id, index)]).length;
}

function countAllDone() {
  const total = itinerary.reduce((sum, day) => sum + day.shots.length, 0);
  const done = itinerary.reduce((sum, day) => sum + countDayDone(day), 0);
  return { total, done, percent: total ? Math.round((done / total) * 100) : 0 };
}

function renderDays() {
  const template = document.querySelector("#dayButtonTemplate");
  dayList.innerHTML = "";

  itinerary.forEach((day) => {
    const localizedDay = localizeDay(day);
    const node = template.content.firstElementChild.cloneNode(true);
    const done = countDayDone(day);
    node.classList.toggle("active", day.id === state.selectedDay);
    node.querySelector(".day-date").textContent = day.date;
    node.querySelector(".day-name").textContent = localizedDay.title;
    node.querySelector(".day-progress").textContent = `${done}/${day.shots.length}`;
    node.addEventListener("click", () => {
      state.selectedDay = day.id;
      render();
    });
    dayList.appendChild(node);
  });
}

function renderHero(day) {
  selectedMood.textContent = day.mood;
  selectedTitle.textContent = `${day.date} ${day.title}`;
  selectedDirectorNote.textContent = day.note;
  heroBadges.innerHTML = day.tags.map((tag) => `<span class="badge">${tag}</span>`).join("");
}

function renderUiText() {
  const labels = uiText[state.lang] || uiText.ko;
  document.documentElement.lang = state.lang;
  document.title = labels.appTitle;
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const key = node.dataset.i18n;
    node.textContent = labels[key] || uiText.ko[key] || node.textContent;
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((node) => {
    const key = node.dataset.i18nAria;
    node.setAttribute("aria-label", labels[key] || uiText.ko[key] || node.getAttribute("aria-label"));
  });
  document.querySelectorAll("[data-i18n-title]").forEach((node) => {
    const key = node.dataset.i18nTitle;
    node.title = labels[key] || uiText.ko[key] || node.title;
  });
  document.querySelectorAll(".lang-button").forEach((button) => {
    button.classList.toggle("active", button.dataset.lang === state.lang);
  });
}

function renderShots(day) {
  const template = document.querySelector("#shotTemplate");
  shotList.innerHTML = "";

  day.shots.forEach(([title, detail, meta], index) => {
    const key = shotKey(day.id, index);
    const node = template.content.firstElementChild.cloneNode(true);
    const checkbox = node.querySelector("input");
    checkbox.checked = Boolean(state.checked[key]);
    node.classList.toggle("done", checkbox.checked);
    node.querySelector("strong").textContent = title;
    node.querySelector("small").textContent = detail;
    node.querySelector(".shot-meta").textContent = meta;
    checkbox.addEventListener("change", () => {
      state.checked[key] = checkbox.checked;
      if (!checkbox.checked) {
        delete state.checked[key];
      }
      save();
      render();
    });
    shotList.appendChild(node);
  });
}

function renderInfo(day) {
  const routes = getLocalizedRoutes(day.id);
  const labels = uiText[state.lang] || uiText.ko;
  scheduleList.innerHTML = `
    <div class="route-day">
      ${routes
        .map(
          (item) => `
            <article class="route-card">
              <header>
                <span class="route-time">${item.time}</span>
                <div>
                  <h4>${item.title}</h4>
                  <p>${item.note}</p>
                </div>
              </header>
              <div class="route-actions">
                ${(item.links || [])
                  .map((link) => `<a class="route-link" href="${link.href}" target="_blank" rel="noreferrer">${link.label}</a>`)
                  .join("")}
              </div>
              ${
                item.alts
                  ? `<div class="route-alts">${item.alts
                      .map((link) => `<a class="route-link alt" href="${link.href}" target="_blank" rel="noreferrer">${labels.alternativePrefix}: ${link.label}</a>`)
                      .join("")}</div>`
                  : ""
              }
            </article>
          `
        )
        .join("")}
    </div>
  `;

  ringPlan.innerHTML = day.ring
    .map(([title, detail], index) => {
      const finalClass = index === day.ring.length - 1 ? " final" : "";
      return `<article class="ring-card${finalClass}"><strong>${title}</strong><p>${detail}</p></article>`;
    })
    .join("");
}

function renderReferenceGuide() {
  const labels = uiText[state.lang] || uiText.ko;
  const guide = referenceGuide[state.lang] || referenceGuide.ko;
  const glossary = shotGlossary[state.lang] || shotGlossary.ko;
  const guideHtml = guide
    .map(
      (section) => `
        <article class="reference-card">
          <strong>${section.title}</strong>
          <ul>${section.items.map((item) => `<li>${item}</li>`).join("")}</ul>
        </article>
      `
    )
    .join("");
  const glossaryTitle = labels.glossaryTitle;
  const glossaryHtml = `
    <article class="reference-card glossary-section">
      <strong>${glossaryTitle}</strong>
      <div class="glossary-grid">
        ${glossary
          .map(
            (item) => `
              <section class="glossary-card">
                <div class="shot-visual ${item.type}" aria-hidden="true">
                  <span class="subject one"></span>
                  <span class="subject two"></span>
                  <span class="detail mark"></span>
                  <span class="detail line"></span>
                  <span class="detail dot"></span>
                </div>
                <div>
                  <h4>${item.term}</h4>
                  <p>${item.meaning}</p>
                  <small>${item.example}</small>
                </div>
              </section>
            `
          )
          .join("")}
      </div>
    </article>
  `;
  referenceGuideEl.innerHTML = glossaryHtml + guideHtml;
}

function renderProgress() {
  const { percent, done, total } = countAllDone();
  const labels = uiText[state.lang] || uiText.ko;
  progressText.textContent = `${percent}%`;
  progressBar.style.width = `${percent}%`;
  progressText.title = `${done}/${total} ${labels.doneTitle}`;
}

function renderMobilePanels() {
  document.querySelectorAll("[data-panel]").forEach((panel) => {
    panel.classList.toggle("active-mobile", panel.dataset.panel === state.mobileTab);
  });
  document.querySelectorAll(".tab").forEach((tab) => {
    tab.classList.toggle("active", tab.dataset.tab === state.mobileTab);
  });
}

function render() {
  const day = getDay();
  renderUiText();
  renderDays();
  renderHero(day);
  renderShots(day);
  renderInfo(day);
  renderReferenceGuide();
  renderProgress();
  renderMobilePanels();
  if (window.lucide) {
    window.lucide.createIcons();
  }
}

document.querySelector("#completeDayBtn").addEventListener("click", () => {
  const day = getDay();
  day.shots.forEach((_, index) => {
    state.checked[shotKey(day.id, index)] = true;
  });
  save();
  render();
});

document.querySelector("#resetBtn").addEventListener("click", () => {
  const labels = uiText[state.lang] || uiText.ko;
  const confirmed = window.confirm(labels.resetConfirm);
  if (!confirmed) return;
  state.checked = {};
  save();
  render();
});

document.querySelector("#printBtn").addEventListener("click", () => {
  window.print();
});

document.querySelector("#exportBtn").addEventListener("click", () => {
  const payload = {
    exportedAt: new Date().toISOString(),
    progress: countAllDone(),
    checked: state.checked
  };
  const blob = new Blob([JSON.stringify(payload, null, 2)], { type: "application/json" });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = "aloha-mv-progress.json";
  link.click();
  URL.revokeObjectURL(url);
});

document.querySelectorAll(".tab").forEach((tab) => {
  tab.addEventListener("click", () => {
    state.mobileTab = tab.dataset.tab;
    renderMobilePanels();
    if (window.lucide) {
      window.lucide.createIcons();
    }
  });
});

document.querySelectorAll(".lang-button").forEach((button) => {
  button.addEventListener("click", () => {
    state.lang = button.dataset.lang;
    localStorage.setItem(langStorageKey, state.lang);
    render();
  });
});

render();
